-- Laboratorio: Control de equipos de laboratorio

-- Esquema
CREATE SCHEMA IF NOT EXISTS inventario;

-- Limpieza para poder volver a ejecutar el script
DROP TABLE IF EXISTS inventario.equipo CASCADE;
DROP TABLE IF EXISTS inventario.tipo_equipo CASCADE;

-- Tabla tipo_equipo (lado "uno" de la relación)
CREATE TABLE inventario.tipo_equipo (
    id_tipo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(255)
);

-- Tabla equipo (lado "muchos"): cada equipo pertenece a un solo tipo
CREATE TABLE inventario.equipo (
    id_equipo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    marca VARCHAR(100),
    -- Solo se permiten estos tres estados
    estado VARCHAR(50) NOT NULL CHECK (estado IN ('Disponible', 'En mantenimiento', 'Fuera de servicio')),
    -- La cantidad no puede ser negativa
    cantidad INTEGER NOT NULL CHECK (cantidad >= 0),
    id_tipo INTEGER NOT NULL,
    -- RESTRICT: no se puede borrar un tipo que tenga equipos
    CONSTRAINT fk_equipo_tipo FOREIGN KEY (id_tipo)
        REFERENCES inventario.tipo_equipo (id_tipo) ON DELETE RESTRICT
);

